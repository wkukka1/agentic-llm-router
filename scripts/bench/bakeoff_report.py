"""Router bake-off headline: per-query routing skill, one row per router.

Joins the 20-model results (``router_bakeoff.py`` -> ``summary_seed<k>.csv``) and the
2-model gpt_4o-vs-gpt_4o_mini results (``routellm_substudy.py`` ->
``routellm_summary_seed<k>.csv``). It ranks routers by what they add **beyond the
query-blind baseline** (each model's train-mean score plus the cost trade-off).
That baseline already reaches almost all of the 20-model AIQ on this benchmark.

Headline columns, per split (test = in-domain, ood = held-out datasets):
* ``headroom``: share of the query-blind -> oracle gap in macro log-cost AIQ that the router captures
  (0 = query-blind, 1 = oracle, < 0 = worse than knowing the averages);
* ``dAIQ [CI]``: macro log-cost AIQ minus query-blind, with a paired bootstrap 95 % CI;
* ``dRho [CI]``: per-query Spearman of the predicted model order minus the blind order;
* ``APGR``: 2-model gap recovered (query-blind = random = 0.5), with a paired bootstrap CI on the
  difference to random.

    python scripts/bench/bakeoff_report.py --bundle-name primary --seed 0
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

# 2-model study names -> 20-model names
ALIAS = {"litellm: adaptive (bandit, trained)": "litellm: adaptive", "ref: oracle": "oracle (cheapest best)",
         "ref: random": "random"}


def _canon(name: str) -> str:
    if name in ALIAS:
        return ALIAS[name]
    if name.startswith("ours: "):
        return name[6:]
    if name.startswith("llmrouter: "):
        return "ext: " + name[11:]
    return name


def _family(name: str) -> str:
    for p, f in (("ext: ", "llmrouter-lib"), ("routellm: ", "RouteLLM"), ("litellm: ", "LiteLLM")):
        if name.startswith(p):
            return f
    if name in ("oracle (cheapest best)", "random", "query-blind (train mean per model)") or \
            name.startswith(("fixed:", "per-dataset")):
        return "reference"
    return "ours"


def _ci(lo, hi) -> str:
    return "" if pd.isna(lo) else f"[{lo:+.3f}, {hi:+.3f}]"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default="investigations/router_bakeoff")
    ap.add_argument("--bundle-name", default="primary")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    d = Path(args.root) / args.bundle_name

    big = pd.read_csv(d / f"summary_seed{args.seed}.csv")
    two = pd.read_csv(d / f"routellm_summary_seed{args.seed}.csv")
    two["router"] = two["router"].map(_canon)
    rows = []
    for split in ("test", "ood"):
        b = big[big["split"] == split].set_index("router")
        t = two[two["split"] == split].set_index("router")
        rnd = t.loc["random", "apgr"] if "random" in t.index else 0.5
        for nm in sorted(set(b.index) | set(t.index)):
            r = {"split": split, "router": nm, "family": _family(nm)}
            if nm in b.index:
                x = b.loc[nm]
                r.update({"aiq_log": x["macro_aiq_log"], "headroom": x.get("headroom_captured"),
                          "dAIQ": x["macro_aiq_log"] - b.loc["query-blind (train mean per model)", "macro_aiq_log"],
                          "dAIQ_lo": x.get("d_macro_aiq_log_vs_anchor_lo"), "dAIQ_hi": x.get("d_macro_aiq_log_vs_anchor_hi"),
                          "regret_lift": x.get("regret_lift"), "rho": x.get("macro_spearman"),
                          "dRho": x.get("d_macro_spearman"), "dRho_lo": x.get("d_macro_spearman_lo"),
                          "dRho_hi": x.get("d_macro_spearman_hi"), "dNDCG3": x.get("d_macro_ndcg@3")})
            if nm in t.index:
                y = t.loc[nm]
                r.update({"apgr": y["apgr"], "apgr_minus_random": y["apgr"] - rnd, "cpt50": y["cpt50"],
                          "dAPGR_lo": y.get("d_apgr_lo"), "dAPGR_hi": y.get("d_apgr_hi")})
            rows.append(r)
    out = pd.DataFrame(rows)
    out.to_csv(d / f"headline_seed{args.seed}.csv", index=False)

    lines = [f"# Router bake-off headline: per-query skill (seed {args.seed})", "",
             "Generated by `scripts/bench/bakeoff_report.py`; see its docstring for definitions. "
             "headroom / dAIQ / dRho are relative to the **query-blind** baseline (each model's train mean "
             "plus the cost trade-off). APGR is the 2-model gpt_4o-vs-gpt_4o_mini test (random = query-blind ≈ 0.5).",
             ""]
    for split, title in (("test", "In-domain (test)"), ("ood", "Out-of-domain (held-out datasets)")):
        s = out[(out["split"] == split) & (out["family"] != "reference")].copy()
        s = s.sort_values("headroom", ascending=False, na_position="last")
        lines += [f"## {title}", "",
                  "| router | family | 20-model AIQ | headroom | dAIQ vs blind [CI] | dRho vs blind [CI] | 2-model APGR [CI vs random] | CPT50 |",
                  "|---|---|---|---|---|---|---|---|"]
        for _, r in s.iterrows():
            f = lambda v, p=3: "" if pd.isna(v) else f"{v:.{p}f}"
            lines.append(f"| {r['router']} | {r['family']} | {f(r.get('aiq_log'))} | "
                         f"{'' if pd.isna(r.get('headroom')) else f'{100 * r.headroom:.0f} %'} | "
                         f"{f(r.get('dAIQ'))} {_ci(r.get('dAIQ_lo'), r.get('dAIQ_hi'))} | "
                         f"{f(r.get('dRho'))} {_ci(r.get('dRho_lo'), r.get('dRho_hi'))} | "
                         f"{f(r.get('apgr'))} {_ci(r.get('dAPGR_lo'), r.get('dAPGR_hi'))} | {'' if pd.isna(r.get('cpt50')) else f'{100 * r.cpt50:.0f} %'} |")
        ref = out[(out["split"] == split) & (out["family"] == "reference")].set_index("router")
        lines += ["", "References: " + ", ".join(
            f"{nm} AIQ {ref.loc[nm, 'aiq_log']:.3f}" for nm in ref.index if not pd.isna(ref.loc[nm].get("aiq_log"))), ""]
    (d / "headline.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
